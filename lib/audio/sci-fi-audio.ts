/**
 * Simulates a dual-frequency biometric voice pulse for Malayalam & English AI Chef speech.
 */
export function playVoiceWaveform(type: "malayalam" | "english" = "malayalam") {
  try {
    const ctx = getAudioContext();
    if (!ctx) return;

    const freq1 = type === "malayalam" ? 440 : 660;
    const freq2 = type === "malayalam" ? 554 : 880;

    const osc1 = ctx.createOscillator();
    const osc2 = ctx.createOscillator();
    const gain = ctx.createGain();

    const now = ctx.currentTime;
    osc1.frequency.setValueAtTime(freq1, now);
    osc2.frequency.setValueAtTime(freq2, now);

    gain.gain.setValueAtTime(0.06, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.15);

    osc1.connect(gain);
    osc2.connect(gain);
    gain.connect(ctx.destination);

    osc1.start(now);
    osc2.start(now);
    osc1.stop(now + 0.15);
    osc2.stop(now + 0.15);
  } catch {}
}
